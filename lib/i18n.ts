export function t(lang: Lang, key: keyof (typeof ui)["en"]): string {
  const dict = ui[lang] as Record<string, string>;
  const fallback = ui.en as Record<string, string>;
  return dict[key] ?? fallback[key] ?? String(key);
}

export function catLabel(lang: Lang, category: string): string {
  const key = `cat${category}`;
  if (key in ui.en) {
    const dict = ui[lang] as Record<string, string>;
    return dict[key] ?? category;
  }
  return category;
}